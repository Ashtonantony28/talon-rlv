"""Fly a mission.

    python -m sim.fly --mission ascent [--no-report]

ascent: closes the M1 design, flies the committed optimal guidance (gnc/ascent_params.yaml) with the
real propellant limit, circularises at apogee and writes docs/design/M2-ascent.{md,png}.
"""
import argparse
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def fly_ascent(spec, design):
    from sim.ascent import Vehicle, simulate, circularization
    from gnc import ascent_opt
    veh = Vehicle.from_design(spec, design)
    p = ascent_opt.load()
    res = simulate(spec, veh, p)
    circ = circularization(spec, veh, res) if res.ok else None
    return veh, p, res, circ


def summary(spec, veh, p, res, circ):
    L = res.log
    i_q = int(np.argmax(L["q"]))
    return {
        "ok": res.ok, "reason": res.reason,
        "params": {"kick_deg": p.kick_deg, "theta0_deg": p.theta0_deg, "c_per_s": p.c_per_s},
        "max_q_pa": L["q"][i_q], "max_q_t": L["t"][i_q], "max_q_alt": L["alt"][i_q], "max_q_mach": L["mach"][i_q],
        "max_accel_g": max(L["accel_g"]),
        "meco": {k: v for k, v in res.events["meco"].items() if k not in ("r", "v")},
        "seco": {k: v for k, v in res.events.get("seco", {}).items() if k not in ("r", "v")},
        "fairing_sep": res.events.get("fairing_sep"),
        "circ": circ,
    }


def report(spec, s, res):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    L = res.log
    t = np.array(L["t"])
    fig, ax = plt.subplots(2, 2, figsize=(9, 6), dpi=130, sharex=True)
    ax[0, 0].plot(t, np.array(L["alt"]) / 1e3); ax[0, 0].set_ylabel("altitude km")
    ax[0, 1].plot(t, L["vel"]); ax[0, 1].set_ylabel("air-relative speed m/s")
    ax[1, 0].plot(t, np.array(L["q"]) / 1e3); ax[1, 0].set_ylabel("dynamic pressure kPa")
    ax[1, 0].axhline(spec["structures"]["design_max_q_pa"] / 1e3, ls="--", c="r", lw=0.8, label="design max-q")
    ax[1, 0].legend(fontsize=7)
    ax[1, 1].plot(t, L["accel_g"]); ax[1, 1].set_ylabel("sensed acceleration g")
    ax[1, 1].axhline(spec["structures"]["max_axial_g"], ls="--", c="r", lw=0.8)
    for a in ax[1]:
        a.set_xlabel("time s")
    for a in ax.flat:
        a.axvline(s["meco"]["t"], c="k", lw=0.5, alpha=0.5)
        a.grid(alpha=0.3)
    fig.suptitle("Talon-1 ascent to 500 km", fontsize=10)
    fig.tight_layout()
    out = ROOT / "docs" / "design"
    fig.savefig(out / "M2-ascent.png")
    m, se, c = s["meco"], s["seco"], s["circ"]
    md = f"""# Talon-1 M2 ascent

Generated by `python -m sim.fly --mission ascent`. Guidance parameters from `gnc/ascent_params.yaml`
(regenerate with `python -m gnc.ascent_opt`).

| Event | Value |
|---|---|
| Guidance | kick {s['params']['kick_deg']:.3f} deg, upper theta0 {s['params']['theta0_deg']:.2f} deg, c {s['params']['c_per_s']:.5f} 1/s |
| Max-q | {s['max_q_pa'] / 1e3:.1f} kPa at T+{s['max_q_t']:.0f} s, {s['max_q_alt'] / 1e3:.1f} km, Mach {s['max_q_mach']:.2f} (design {spec['structures']['design_max_q_pa'] / 1e3:.0f} kPa) |
| Max sensed acceleration | {s['max_accel_g']:.2f} g (limit {spec['structures']['max_axial_g']:.1f} g, throttled) |
| MECO / staging | T+{m['t']:.1f} s, {m['alt'] / 1e3:.1f} km, {m['v_rel']:.0f} m/s air-relative, flight path {m['flight_path_deg']:.1f} deg |
| Fairing separation | T+{s['fairing_sep']['t']:.1f} s, {s['fairing_sep']['alt'] / 1e3:.1f} km |
| SECO | T+{se['t']:.1f} s, insertion orbit {se['perigee'] / 1e3:.1f} x {se['apogee'] / 1e3:.1f} km |
| Apogee circularisation | {c['dv']:.1f} m/s, {c['prop_needed']:.1f} kg |
| Final orbit | {c['final_alt_km']:.1f} km circular |
| Upper-stage propellant margin | {c['margin_kg']:.1f} kg |

![ascent](M2-ascent.png)

Notes: point-mass ascent with perfect attitude tracking (the 6-DOF TVC loop arrives in M3); zero-alpha
gravity turn, so the design max-q alpha of {spec['structures']['design_alpha_maxq_deg']:.0f} deg is the wind allowance.
The positive margin means the M1 dv budget (9300 m/s) was slightly conservative.
"""
    (out / "M2-ascent.md").write_text(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mission", choices=["ascent"], required=True)
    ap.add_argument("--no-report", action="store_true")
    a = ap.parse_args()
    from design import spec as dspec, closure
    sp = dspec.load()
    d = closure.close(sp)
    veh, p, res, circ = fly_ascent(sp, d)
    if not res.ok:
        raise SystemExit(f"ascent failed: {res.reason}")
    s = summary(sp, veh, p, res, circ)
    if not a.no_report:
        report(sp, s, res)
    print(f"orbit {circ['final_alt_km']:.1f} km, margin {circ['margin_kg']:.1f} kg, max-q {s['max_q_pa'] / 1e3:.1f} kPa, "
          f"max {s['max_accel_g']:.2f} g")


if __name__ == "__main__":
    main()

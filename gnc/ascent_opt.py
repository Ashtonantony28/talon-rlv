"""Optimise the ascent guidance parameters (M2).

Decision variables: booster pitch-kick angle and the upper stage's linear-tangent parameters.
Objective: maximise upper-stage propellant left after the apogee circularisation burn, subject to
insertion apogee = target (SECO event) and perigee >= floor (quadratic penalty). A coarse grid
seeds a Nelder-Mead polish.
"""
import itertools
import numpy as np
from scipy.optimize import minimize
from sim.ascent import simulate, circularization, AscentParams
from sim import gravity

PENALTY = 2000.0  # kg per km^2 of perigee shortfall (keeps the floor effectively hard)


def cost(spec, veh, x, dt):
    p = AscentParams(*x)
    res = simulate(spec, veh, p, dt=dt, record=False, allow_overrun=True)
    floor = spec["ascent"]["min_perigee_km"]
    if res.ok:
        c = circularization(spec, veh, res)
        short = max(0.0, floor - res.events["seco"]["perigee"] / 1e3)
        return -c["margin_kg"] + PENALTY * short ** 2
    if res.reason == "upper stage depleted":
        return 1e3 + 5.0 * energy_deficit_mps(spec, res.events["depletion"])
    return 1e6 - 100.0 * max(res.log_max_alt_km, 0.0)   # crash: reward climbing higher


def energy_deficit_mps(spec, state):
    """Speed shortfall at the current radius to reach the target circular orbit's energy."""
    r, v = np.linalg.norm(state["r"]), np.linalg.norm(state["v"])
    rt = gravity.R_EQ + spec["ascent"]["target_apogee_km"] * 1e3
    e_t = -gravity.MU / (2 * rt)
    v_req = np.sqrt(max(0.0, 2 * (e_t + gravity.MU / r)))
    return max(0.0, v_req - v)


def optimize(spec, veh, dt_fine=0.2, verbose=False):
    grid = itertools.product([1.0, 2.0, 3.0, 4.0, 6.0], [10.0, 20.0, 30.0, 40.0], [0.001, 0.002, 0.003, 0.004])
    scored = sorted((cost(spec, veh, g, dt_fine), g) for g in grid)
    if verbose:
        print("grid best", scored[:3])
    x0 = np.array(scored[0][1])
    # Nelder-Mead with restarts: a fresh simplex around the last best point until a restart no
    # longer improves the objective (one pass can collapse early on this slightly noisy objective)
    step = np.array([1.0, 5.0, 0.001])
    best = None
    for _ in range(6):
        simplex = np.vstack([x0, x0 + np.diag(step)])
        res = minimize(lambda x: cost(spec, veh, x, dt_fine), x0, method="Nelder-Mead",
                       options={"xatol": 1e-4, "fatol": 0.05, "maxiter": 300, "initial_simplex": simplex})
        if best is not None and res.fun > best.fun - 0.1:
            best = res if res.fun < best.fun else best
            break
        best, x0 = res, res.x
        step = step * 0.3
    res = best
    if verbose:
        print(res)
    return AscentParams(*res.x), res


PARAMS_PATH = __import__("pathlib").Path(__file__).resolve().parent / "ascent_params.yaml"


def save(p, path=PARAMS_PATH):
    import yaml
    path.write_text("# Generated by `python -m gnc.ascent_opt` from the closed M1 design. Regenerating is a\n"
                    "# reviewed change (CLAUDE.md rule 2).\n" +
                    yaml.safe_dump({"kick_deg": float(p.kick_deg), "theta0_deg": float(p.theta0_deg),
                                    "c_per_s": float(p.c_per_s)}))


def load(path=PARAMS_PATH):
    import yaml
    return AscentParams(**yaml.safe_load(path.read_text()))


if __name__ == "__main__":
    from design import spec as dspec, closure
    from sim.ascent import Vehicle
    sp = dspec.load()
    veh = Vehicle.from_design(sp, closure.close(sp))
    p, res = optimize(sp, veh, verbose=False)
    save(p)
    print(p, "objective", res.fun)

"""Close the design and write the M1 design package.

    python -m cad.build [--out build/]

Outputs: STEP + STL of the vehicle, design.json (sizing, CAD dry masses, thickness, margins,
mass properties) and docs/design/M1-design.md (human-readable summary).
"""
import argparse
import json
from pathlib import Path
import numpy as np
from design import spec as dspec, closure, sizing
from design.spec import G0
from cad import vehicle as cv

ROOT = Path(__file__).resolve().parents[1]


def summarize(sp, d):
    s = d.sizing
    parts = d.parts
    full = cv.mass_properties(sp, parts)
    dry_stack = cv.mass_properties(sp, parts, lambda p: p.kind != "propellant")
    booster_dry = cv.mass_properties(sp, parts, lambda p: p.stage == "booster" and p.kind != "propellant")
    booster_land = cv.mass_properties(sp, parts, lambda p: p.stage == "booster" and p.kind != "propellant")
    mp = lambda t: {"mass_kg": t[0], "cg_z_m": t[1][2], "inertia_kgm2": np.round(t[2], 3).tolist()}
    chk = sizing.engine_check(sp, s)
    return {
        "sizing": s.as_dict(),
        "struct_fraction": d.eps,
        "closure_iterations": d.iterations,
        "closure_history": d.history,
        "cad_dry_kg": d.dry,
        "glow_cad_kg": full[0],
        "length_m": d.info["length"],
        "z_sep_m": d.info["z_sep"],
        "thrust_to_weight": {k: float(v) for k, v in chk.items() if k.startswith("tw")},
        "mass_properties": {"liftoff": mp(full), "dry_stack": mp(dry_stack), "booster_dry": mp(booster_dry)},
        "walls": {k: {"t_mm": v["t"] * 1e3, "min_ratio": v["min_ratio"], "governing": v["governing"]}
                  for k, v in d.margins.items()},
        "parts": {p.name: {"stage": p.stage, "kind": p.kind, "mass_kg": p.props()[0]} for p in parts},
    }


def markdown(sp, j):
    s = j["sizing"]
    L = []
    L.append("# Talon-1 M1 design package\n")
    L.append("Generated by `python -m cad.build` from `spec/vehicle.yaml`. Do not edit by hand.\n")
    L.append("## Vehicle\n")
    L.append(f"| Quantity | Value |\n|---|---|")
    L.append(f"| Payload to 500 km LEO | {s['payload']:.0f} kg |")
    L.append(f"| Gross lift-off mass (sizing / CAD) | {s['glow']:.0f} / {j['glow_cad_kg']:.0f} kg |")
    L.append(f"| Length x diameter | {j['length_m']:.2f} m x {sp['diameter_m']:.2f} m |")
    L.append(f"| Booster dv (ascent) / recovery reserve | {s['booster']['dv_ascent']:.0f} / {sp['mission']['booster_recovery_dv_mps']:.0f} m/s |")
    L.append(f"| Upper stage dv | {s['upper']['dv_ascent']:.0f} m/s |")
    L.append(f"| Lift-off T/W, upper ignition T/W | {j['thrust_to_weight']['tw_liftoff']:.2f}, {j['thrust_to_weight']['tw_upper']:.2f} |")
    L.append(f"| Closure iterations | {j['closure_iterations']} |\n")
    L.append("## Stages\n")
    L.append("| Stage | Gross kg | Propellant kg (ascent + recovery) | Dry kg sizing | Dry kg CAD | Structural fraction |\n|---|---|---|---|---|---|")
    for stg in ("booster", "upper"):
        st = s[stg]
        L.append(f"| {stg} | {st['gross']:.0f} | {st['prop_ascent']:.0f} + {st['prop_recovery']:.0f} | {st['dry']:.1f} | "
                 f"{j['cad_dry_kg'][stg]:.1f} | {j['struct_fraction'][stg]:.4f} |")
    L.append("\n## Walls and margins\n")
    L.append(f"Ratio = capacity / (FS {sp['structures']['factor_of_safety']} x limit load); >= 1 is a positive margin.\n")
    L.append("| Barrel | t (mm) | Min ratio | Governing case/mode |\n|---|---|---|---|")
    for k, w in j["walls"].items():
        L.append(f"| {k} | {w['t_mm']:.2f} | {w['min_ratio']:.2f} | {w['governing']} |")
    L.append("\n## Mass properties (about CoM, z from booster base)\n")
    L.append("| Configuration | Mass kg | CG z m | Ixx, Iyy, Izz kg m^2 |\n|---|---|---|---|")
    for k, m in j["mass_properties"].items():
        I = m["inertia_kgm2"]
        L.append(f"| {k} | {m['mass_kg']:.1f} | {m['cg_z_m']:.3f} | {I[0][0]:.0f}, {I[1][1]:.0f}, {I[2][2]:.0f} |")
    L.append("\n## Modelling notes\n")
    L.append("- Booster ascent Isp is the mean of SL and vacuum; M2 replaces it with the trajectory-integrated value.")
    L.append("- Fairing counted as upper-stage dry mass for its whole burn (conservative).")
    L.append("- Max-q loads use the design values in the spec; M2 checks the trajectory stays within them.")
    L.append("- Bending ignores inertial relief and pressure stabilisation (both conservative).")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "build"))
    ap.add_argument("--no-export", action="store_true")
    a = ap.parse_args()
    sp = dspec.load()
    d = closure.close(sp)
    j = summarize(sp, d)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "design.json").write_text(json.dumps(j, indent=1, default=float))
    docs = ROOT / "docs" / "design"
    docs.mkdir(parents=True, exist_ok=True)
    (docs / "M1-design.md").write_text(markdown(sp, j))
    if not a.no_export:
        cv.export(d.parts, out)
    print(f"GLOW {j['glow_cad_kg']:.0f} kg, dry booster {d.dry['booster']:.0f} kg, upper {d.dry['upper']:.0f} kg, "
          f"{d.iterations} iterations -> {out}")


if __name__ == "__main__":
    main()
